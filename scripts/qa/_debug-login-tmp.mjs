import { chromium } from 'playwright';
const BASE = 'http://localhost:5195';
const b = await chromium.launch();
const c = await b.newContext({ viewport: { width: 1440, height: 900 } });
const page = c.newPage ? await c.newPage() : null;
page.on('console', msg => console.log('[console]', msg.type(), msg.text()));
page.on('pageerror', err => console.log('[pageerror]', err.message));
await page.goto(`${BASE}/compte`, { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(1500);
await page.screenshot({ path: '/tmp/dbg1-before-click.png' });
await page.getByRole('button', { name: /se connecter/i }).first().click();
await page.waitForTimeout(800);
await page.screenshot({ path: '/tmp/dbg2-modal-open.png' });
const count = await page.getByRole('button', { name: /se connecter/i }).count();
console.log('nb boutons "se connecter":', count);
await page.getByPlaceholder(/courriel/i).fill(process.env.KRYSTINE_ADMIN_PW ? 'admin@krystinestlaurent.ca' : 'x');
await page.getByPlaceholder(/mot de passe/i).fill(process.env.KRYSTINE_ADMIN_PW || 'x');
await page.screenshot({ path: '/tmp/dbg3-filled.png' });
await b.close();
