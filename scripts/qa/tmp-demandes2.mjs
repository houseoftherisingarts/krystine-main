import { chromium } from 'playwright';
import fs from 'node:fs';
const token = fs.readFileSync('/tmp/jeton-krystine.txt', 'utf8').trim();
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
p.on('console', (m) => { if (m.type() === 'error' && !m.text().includes('frame-ancestors')) console.log('console:', m.text().slice(0, 200)); });
p.on('requestfailed', (r) => console.log('failed:', r.url().slice(0, 120), r.failure()?.errorText));
await p.goto('http://localhost:5199/admin/demander-un-changement', { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(2500);
await p.evaluate(async (t) => {
  const src = await fetch('/src/firebase/auth.ts').then((r) => r.text());
  const url = src.match(/"([^"]*firebase_auth\.js[^"]*)"/)[1];
  const a = await import(url);
  const { auth } = await import('/src/firebase.ts');
  await a.signInWithCustomToken(auth, t);
}, token);
await p.waitForTimeout(8000);
const txt = await p.locator('body').innerText();
console.log('vos demandes present:', txt.includes('Vos demandes'), '| h3 count:', await p.locator('h3').count());
console.log(txt.slice(txt.indexOf('Demander un changement', 500), txt.indexOf('Demander un changement', 500) + 500).replace(/\n+/g, ' | '));
await b.close();
