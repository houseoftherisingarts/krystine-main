import { chromium } from 'playwright';
const BASE = 'http://localhost:3033';
const b = await chromium.launch();
const c = await b.newContext({ viewport: { width: 1440, height: 1200 } });
const p = await c.newPage();
await p.goto(BASE + '/compte', { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(1800);
await p.getByRole('button', { name: /Accéder à mon compte/i }).first().click({ timeout: 15000 });
await p.waitForTimeout(700);
await p.getByText('Déjà un compte').click({ timeout: 10000 });
await p.waitForTimeout(600);
await p.getByPlaceholder(/Courriel/i).fill('admin@krystinestlaurent.ca');
await p.getByPlaceholder(/Mot de passe/i).fill('cJOOAoXbEsKBuoTVMDBs4CYI');
await p.getByRole('button', { name: /^Se connecter$/i }).click();
await p.waitForTimeout(3500);
await p.goto(BASE + '/compte?onglet=telechargements', { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(2200);
const entete = p.getByText('Santé la vie', { exact: true }).first();
await entete.scrollIntoViewIfNeeded();
await entete.click({ timeout: 10000 });
await p.waitForTimeout(700);
await entete.scrollIntoViewIfNeeded();
await p.screenshot({ path: 'scripts/qa/shots/compte-saisons-1440.png', fullPage: true });
console.log('capturé compte-saisons-1440 (ouvert)');
await p.setViewportSize({ width: 390, height: 1200 });
await p.waitForTimeout(400);
await entete.scrollIntoViewIfNeeded();
await p.screenshot({ path: 'scripts/qa/shots/compte-saisons-390.png', fullPage: true });
console.log('capturé compte-saisons-390 (ouvert)');
await b.close();
